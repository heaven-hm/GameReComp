"""Deterministic tests for the fail-closed batch stress runner.

No real game binaries or assets are used. The only PE input is the checked-in
synthetic ``pe32-minimal.exe`` fixture (generated by
``tests/fixtures/make_pe32_fixture.py``), copied into temporary game roots.
Native stand-ins are tiny Python scripts that emit a deterministic BMP frame or
deterministic CLI output through the same environment variables the real native
runtimes use. A meta-test proves fabricated hashes and claims cannot yield PASS.
"""
from __future__ import annotations

import contextlib
import hashlib
import io
import json
import os
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tools import corpus_stress as cs  # noqa: E402

FIXTURE = ROOT / "tests" / "fixtures" / "pe32-minimal.exe"
GENERATED_AT = "2026-01-01T00:00:00Z"

# A deterministic non-blank 2x2 BMP frame plus the per-game TMPDIR in stdout,
# so the test can prove TMPDIR isolation without writing into a game directory.
RENDERER = r'''#!/usr/bin/env python3
import os, struct
from pathlib import Path
d = Path(os.environ["RECOMP_SCREENSHOT"])
d.mkdir(parents=True, exist_ok=True)
w = h = 2
stride = ((w * 3 + 3) // 4) * 4
data = bytearray(54 + stride * h)
data[:2] = b"BM"
struct.pack_into("<I", data, 10, 54)
struct.pack_into("<I", data, 14, 40)
struct.pack_into("<ii", data, 18, w, h)
struct.pack_into("<H", data, 26, 1)
struct.pack_into("<H", data, 28, 24)
pixels = [b"\x01\x02\x03", b"\x04\x05\x06", b"\x07\x08\x09", b"\x04\x05\x06"]
for y in range(h):
    for x in range(w):
        off = 54 + y * stride + x * 3
        data[off:off + 3] = pixels[y * w + x]
(d / "frame-0000.bmp").write_bytes(data)
print("TMPDIR=" + os.environ.get("TMPDIR", ""))
'''

BLANK_RENDERER = RENDERER.replace(
    'pixels = [b"\\x01\\x02\\x03", b"\\x04\\x05\\x06", '
    'b"\\x07\\x08\\x09", b"\\x04\\x05\\x06"]',
    'pixels = [b"\\x01\\x02\\x03"] * 4')

CLI_NATIVE = '''#!/usr/bin/env python3
print("stress-cli-v1")
'''
CLI_OUTPUT = b"stress-cli-v1\n"


def sha_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def make_game(root: Path, name: str, *, overlay: bytes = b"",
              renderer: str = RENDERER, with_pipeline: bool = False) -> dict:
    """Create a synthetic game directory (synthetic PE, no game assets)."""
    folder = root / name
    folder.mkdir(parents=True, exist_ok=True)
    exe = folder / f"{name}.exe"
    exe.write_bytes(FIXTURE.read_bytes() + overlay)
    native = folder / "native"
    native.write_text(renderer)
    os.chmod(native, 0o755)
    info = {
        "name": name, "dir": folder, "exe": exe, "native": native,
        "sha_exe": sha_bytes(exe.read_bytes()),
        "sha_native": sha_bytes(native.read_bytes()),
    }
    if with_pipeline:
        (folder / "report.json").write_text(json.dumps({
            "input": str(exe),
            "manifest": {"input_sha256": info["sha_exe"],
                         "binary": {"path": str(native),
                                    "sha256": info["sha_native"],
                                    "size": native.stat().st_size}},
            "outcome": {"status": "scenario-pass", "reason": "test oracle"},
            "stages": [{"name": "compile", "status": "ok"}],
            "score": 42,
        }))
    return info


def write_scenario(game: dict, output: bytes = CLI_OUTPUT) -> Path:
    path = game["dir"] / "scenario.json"
    path.write_text(json.dumps({
        "args": [], "expected_exit": 0,
        "expected_output_sha256": sha_bytes(output),
    }))
    return path


def write_coverage(root: Path, sha_exe: str, missing: bool = False) -> Path:
    path = root / "coverage.json"
    missing_map = {"KERNEL32.dll": ["GetTickCount"]} if missing else {}
    path.write_text(json.dumps({"inputs": {sha_exe: {"missing": missing_map}}}))
    return path


def oracle_record(game: dict, evidence_path: Path, **overrides) -> dict:
    record = {
        "game": game["name"], "oracle": "original-windows",
        "oracle_verified": True,
        "input_sha256": game["sha_exe"],
        "native_sha256": game["sha_native"],
        "scenario": "boot-to-menu",
        "scenario_evidence": "original and native menus match at frame 12",
        "evidence_path": str(evidence_path),
        "evidence_sha256": sha_bytes(evidence_path.read_bytes()),
    }
    record.update(overrides)
    return record


def write_oracle(root: Path, *records: dict) -> Path:
    path = root / "oracle.json"
    path.write_text(json.dumps({"records": list(records)}))
    return path


def run_batch(roots: list[Path], out: Path, *, extra: list[str] | None = None,
              jobs: int = 1) -> dict:
    argv = ["--generated-at", GENERATED_AT, "--timeout", "5",
            "--jobs", str(jobs)]
    for root in roots:
        argv += ["--games-root", str(root)]
    argv += ["--out", str(out), "--json", str(out / "batch.json"),
             "--markdown", str(out / "batch.md")]
    argv += list(extra or [])
    with contextlib.redirect_stdout(io.StringIO()):
        rc = cs.main(argv)
    assert rc == 0, f"main returned {rc}"
    return json.loads((out / "batch.json").read_text(encoding="utf-8"))


class DiscoveryTest(unittest.TestCase):
    def test_discovers_only_supplied_roots_and_deduplicates_names(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            first, second = base / "a", base / "b"
            game = make_game(first, "alpha")
            make_game(second / "nested", "alpha", overlay=b"different")  # type: ignore[arg-type]
            make_game(second, "beta")
            (first / "notes.txt").write_text("not an executable")
            games, inputs = cs.discover_games([str(first), str(second)])
            self.assertEqual([g["name"] for g in games],
                             ["alpha", "beta", "alpha-alpha"])
            self.assertEqual(len(inputs), 2)
            self.assertTrue(all(rec["status"] == "ok" for rec in inputs))
            self.assertEqual(inputs[0]["discovered"], 1)
            self.assertEqual(inputs[1]["discovered"], 2)
            # A missing root is reported, never silently skipped.
            _, bad = cs.discover_games([str(base / "absent")])
            self.assertEqual(bad[0]["status"], "MISSING_INPUT")
            self.assertEqual(game["name"], "alpha")

    def test_sidecars_are_scoped_to_the_game_directory(self):
        with tempfile.TemporaryDirectory() as tmp:
            game = make_game(Path(tmp), "solo", with_pipeline=True)
            side = cs.sidecars({"name": "solo", "dir": str(game["dir"]),
                                "path": str(game["exe"])})
            self.assertEqual(side["native"], str(game["native"]))
            self.assertTrue(side["pipeline_report"].endswith("report.json"))
            self.assertIsNone(side["oracle"])
            self.assertIsNone(side["coverage"])


class BatchTest(unittest.TestCase):
    def test_batch_records_evidence_and_isolated_tmpdirs(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            root_a, root_b = base / "corpusA", base / "corpusB"
            games = [make_game(root_a, "game-one", overlay=b"one"),
                     make_game(root_a, "game-two", overlay=b"two"),
                     make_game(root_b, "game-three", overlay=b"three")]
            before = {g["dir"]: sorted(p.name for p in g["dir"].iterdir())
                      for g in games}
            out = base / "out"
            report = run_batch([root_a, root_b], out, jobs=2,
                               extra=["--limit", "2"])
            summary = report["summary"]
            self.assertEqual(summary["total"], 3)
            self.assertEqual(summary["attempted"], 2)
            self.assertEqual(summary["by_status"]["PARTIAL"], 2)
            self.assertEqual(summary["by_status"]["NOT TESTED"], 1)
            self.assertEqual(report["generated_at"], GENERATED_AT)

            attempted = report["games"][:2]
            self.assertEqual([r["game"] for r in attempted],
                             ["game-one", "game-two"])
            tmpdirs = set()
            for record in attempted:
                self.assertEqual(record["verdict"], cs.PARTIAL)
                self.assertEqual(record["original"]["status"], "ok")
                self.assertTrue(cs.am.is_sha256(record["original"]["sha256"]))
                self.assertEqual(record["original"]["architecture"], "i386")
                self.assertIn("KERNEL32.dll",
                              record["imports"]["declared_dlls"])
                self.assertTrue(cs.am.is_sha256(record["native"]["sha256"]))
                self.assertEqual(record["launch"]["exit_code"], 0)
                self.assertIsInstance(record["launch"]["seconds"], (int, float))
                self.assertEqual(record["frames"]["count"], 1)
                frame = record["frames"]["frames"][0]
                self.assertTrue(cs.am.is_sha256(frame["sha256"]))
                self.assertEqual((frame["width"], frame["height"]), (2, 2))
                self.assertEqual(frame["distinct_colors"], 3)
                self.assertTrue(frame["marker"].startswith("OK"))
                self.assertTrue(record["reasons"])
                # Journal on disk, work tree under --out, unique TMPDIR.
                journal = Path(record["json"])
                self.assertTrue(journal.is_file())
                self.assertEqual(json.loads(journal.read_text())["verdict"],
                                 cs.PARTIAL)
                tmpdir = Path(record["tmp_dir"])
                self.assertTrue(tmpdir.is_dir())
                self.assertTrue(tmpdir.is_relative_to(out.resolve()))
                tmpdirs.add(str(tmpdir))
                log = Path(record["launch"]["log"]).read_text()
                self.assertIn(f"TMPDIR={tmpdir}", log)
                self.assertTrue(Path(record["project_dir"]).is_relative_to(
                    out.resolve()))
            self.assertEqual(len(tmpdirs), 2)

            skipped = report["games"][2]
            self.assertEqual(skipped["verdict"], cs.NOT_TESTED)
            self.assertFalse(skipped["launch"]["executed"])
            self.assertTrue(any("--limit" in r for r in skipped["reasons"]))
            self.assertTrue(Path(skipped["json"]).is_file())

            # Generated files never land in the user's game directories.
            for game in games:
                self.assertEqual(
                    sorted(p.name for p in game["dir"].iterdir()),
                    before[game["dir"]])

            markdown = (out / "batch.md").read_text(encoding="utf-8")
            self.assertIn("Corpus stress batch report", markdown)
            self.assertIn("-m tools.corpus_stress", markdown)
            self.assertIn("--limit 2", markdown)
            self.assertIn("**PARTIAL**", markdown)
            self.assertIn("**NOT TESTED**", markdown)
            self.assertIn("colours=3", markdown)
            self.assertNotIn(str(Path.home()), markdown)

    def test_no_run_is_build_only_and_invalid_pe_is_blocked(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            make_game(base / "roots" / "built", "built")
            bad_dir = base / "roots" / "bad"
            bad_dir.mkdir(parents=True)
            (bad_dir / "bad.exe").write_bytes(b"MZnot-a-pe")
            out = base / "out"
            report = run_batch([base / "roots"], out, extra=["--no-run"])
            by_name = {g["game"]: g for g in report["games"]}
            self.assertEqual(by_name["built"]["verdict"], cs.BUILD_ONLY)
            self.assertFalse(by_name["built"]["launch"]["executed"])
            self.assertEqual(by_name["bad"]["verdict"], cs.BLOCKED)
            self.assertTrue(any("original PE" in r
                                for r in by_name["bad"]["reasons"]))

    def test_blank_frame_is_fail(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            make_game(base / "corpus", "blank", renderer=BLANK_RENDERER)
            report = run_batch([base / "corpus"], base / "out")
            record = report["games"][0]
            self.assertEqual(record["verdict"], cs.FAIL)
            self.assertEqual(record["frames"]["blank_count"], 1)
            self.assertTrue(any("render evidence" in r
                                for r in record["reasons"]))

    def test_cli_scenario_reproduces_process_evidence(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            game = make_game(base / "corpus", "cliapp")
            game["native"].write_text(CLI_NATIVE)
            os.chmod(game["native"], 0o755)
            game["sha_native"] = sha_bytes(game["native"].read_bytes())
            (game["dir"] / "report.json").unlink(missing_ok=True)
            write_scenario(game)
            report = run_batch([base / "corpus"], base / "out")
            record = report["games"][0]
            self.assertEqual(record["verdict"], cs.PARTIAL)
            self.assertEqual(record["kind"], "cli")
            self.assertTrue(record["cli_evidence"]["reproduced"])
            self.assertEqual(record["launch"]["exit_code"], 0)
            self.assertEqual(record["frames"]["count"], 0)
            self.assertEqual(Path(record["launch"]["log"]).read_bytes(),
                             CLI_OUTPUT)

    def test_jobs_matches_serial_for_verdicts_and_hashes(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            root = base / "corpus"
            for index in range(3):
                make_game(root, f"game{index}", overlay=bytes([index]))
            serial = run_batch([root], base / "out-serial", jobs=1)
            parallel = run_batch([root], base / "out-parallel", jobs=3)
            keys = ("game", "verdict", "kind", "exit_code")
            def slim(report):
                return [{"game": g["game"], "verdict": g["verdict"],
                         "kind": g["kind"],
                         "exit_code": g["launch"]["exit_code"],
                         "original": g["original"]["sha256"],
                         "native": g["native"]["sha256"],
                         "frames": [f["sha256"] for f in g["frames"]["frames"]]}
                        for g in report["games"]]
            self.assertEqual(slim(serial), slim(parallel))
            self.assertEqual(serial["summary"], parallel["summary"])
            self.assertEqual(keys[0], "game")

    def test_out_inside_a_games_root_is_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            root = base / "corpus"
            make_game(root, "safe")
            with contextlib.redirect_stdout(io.StringIO()), \
                    contextlib.redirect_stderr(io.StringIO()):
                rc = cs.main(["--games-root", str(root),
                              "--out", str(root / "generated")])
            self.assertEqual(rc, 2)
            self.assertFalse((root / "generated").exists())

    def test_run_pipeline_uses_isolated_project_dir(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            root = base / "corpus"
            game = make_game(root, "piped")
            (game["native"]).unlink()  # build-only; the pipeline run is the point
            out = base / "out"
            called = {}

            def fake_pipeline(name, original_path, project_dir, tmp_dir, timeout):
                called.update(name=name, project=Path(project_dir),
                              tmp=Path(tmp_dir), original=original_path)
                return {"status": "ok", "report": None, "command": ["fake"],
                        "exit_code": 1, "reason": "no real pipeline in a test"}

            with mock.patch.object(cs, "invoke_pipeline", fake_pipeline):
                report = run_batch([root], out, extra=["--run-pipeline"])
            self.assertEqual(called["name"], "piped")
            self.assertTrue(called["project"].is_relative_to(out.resolve()))
            self.assertTrue(called["tmp"].is_relative_to(out.resolve()))
            record = report["games"][0]
            self.assertEqual(record["commands"]["pipeline"], ["fake"])
            self.assertEqual(record["verdict"], cs.BLOCKED)
            self.assertTrue(any("no real pipeline" in r
                                for r in record["pipeline"]["reasons"]))


class OracleTest(unittest.TestCase):
    def _setup(self, tmp: Path) -> dict:
        base = Path(tmp)
        root = base / "corpus"
        game = make_game(root, "oracled", with_pipeline=True)
        evidence = game["dir"] / "evidence.json"
        evidence.write_text("original and native menus match at frame 12")
        coverage = write_coverage(base, game["sha_exe"])
        oracle = write_oracle(base, oracle_record(game, evidence))
        info = dict(game)
        info.update(base=base, root=root, out=base / "out",
                    evidence=evidence, coverage=coverage, oracle=oracle)
        return info

    def test_valid_oracle_promotes_evidenced_game_to_pass(self):
        with tempfile.TemporaryDirectory() as tmp:
            info = self._setup(tmp)
            report = run_batch(
                [info["root"]], info["out"],
                extra=["--oracle-evidence", str(info["oracle"]),
                       "--api-coverage", str(info["coverage"])])
            record = report["games"][0]
            self.assertEqual(record["verdict"], cs.PASS, record["reasons"])
            self.assertTrue(record["oracle"]["valid"])
            self.assertTrue(any("validated original-Windows oracle" in r
                                for r in record["reasons"]))
            self.assertEqual(record["imports"]["status"], "CLEAR")
            self.assertEqual(record["pipeline"]["verification_status"],
                             "scenario-pass")

    def test_fabricated_hashes_and_claims_never_produce_pass(self):
        """Meta-test: a claim is not evidence, even with a perfect build."""
        with tempfile.TemporaryDirectory() as tmp:
            info = self._setup(tmp)
            report = run_batch(
                [info["root"]], info["out"],
                extra=["--oracle-evidence", str(info["oracle"]),
                       "--api-coverage", str(info["coverage"])])
            good = report["games"][0]
            self.assertEqual(good["verdict"], cs.PASS, good["reasons"])

            oracles, coverage, _ = cs.load_evidence(
                [str(info["oracle"])], [str(info["coverage"])])
            valid = cs.oracle_for(oracles, "oracled")
            self.assertIsNotNone(valid)
            evidence_sha = sha_bytes(info["evidence"].read_bytes())

            cases = {
                "fabricated-input-hash": (
                    {"input_sha256": "0" * 64}, {}, None),
                "fabricated-native-hash": (
                    {"native_sha256": "1" * 64}, {}, None),
                "fabricated-evidence-hash": (
                    {"evidence_sha256": "2" * 64}, {}, None),
                "oracle-flag-false": (
                    {"oracle_verified": False}, {}, None),
                "fake-oracle-name": (
                    {"oracle": "dummy-device"}, {}, None),
                "unexecuted-oracle-label": (
                    {"oracle": "windows-oracle-unexecuted"}, {}, None),
                "no-scenario": (
                    {"scenario": ""}, {}, None),
                "no-scenario-evidence": (
                    {"scenario_evidence": ""}, {}, None),
                "other-game": (
                    {"game": "a-different-game"}, {}, None),
                "unresolved-imports": (
                    {}, {"unresolved_system_imports": 1}, None),
                "failed-pipeline-stage": (
                    {}, {}, {"stage_failed": "compile"}),
            }
            for label, (oracle_patch, import_patch, pipeline_patch) \
                    in cases.items():
                with self.subTest(case=label):
                    oracle = dict(valid)
                    oracle.update(oracle_patch)
                    oracle["checks"] = dict(valid["checks"])
                    if "oracle_verified" in oracle_patch:
                        oracle["checks"]["has_real_oracle_flag"] = False
                        oracle["valid"] = False
                    if "oracle" in oracle_patch:
                        oracle["checks"]["has_real_oracle_name"] = False
                        oracle["valid"] = False
                    if "scenario" in oracle_patch and not oracle_patch["scenario"]:
                        oracle["checks"]["has_scenario"] = False
                        oracle["valid"] = False
                    if "scenario_evidence" in oracle_patch \
                            and not oracle_patch["scenario_evidence"]:
                        oracle["checks"]["has_scenario_evidence"] = False
                        oracle["valid"] = False
                    if "evidence_sha256" in oracle_patch:
                        oracle["checks"]["evidence_hash_matches"] = False
                        oracle["valid"] = False
                    if "game" in oracle_patch:
                        oracle["valid"] = False  # no matching record at all
                    candidate = dict(good)
                    candidate["imports"] = dict(good["imports"])
                    candidate["imports"].update(import_patch)
                    candidate["pipeline"] = dict(good["pipeline"])
                    candidate["pipeline"].update(pipeline_patch or {})
                    verdict, reasons = cs.classify_stress(candidate, oracle)
                    self.assertNotEqual(verdict, cs.PASS, reasons)
                    self.assertTrue(any("PASS withheld" in r
                                        for r in reasons), reasons)

            # The same fabrication through the real CLI must also fail closed.
            fake = write_oracle(
                info["base"], oracle_record(
                    info, info["evidence"],
                    input_sha256="0" * 64))
            fake_out = info["base"] / "out-fake"
            fake_report = run_batch(
                [info["root"]], fake_out,
                extra=["--oracle-evidence", str(fake),
                       "--api-coverage", str(info["coverage"])])
            self.assertNotEqual(fake_report["games"][0]["verdict"], cs.PASS)
            self.assertEqual(fake_report["games"][0]["verdict"], cs.PARTIAL)
            # The honest evidence hash is still computed, not copied from a claim.
            self.assertEqual(good["frames"]["frames"][0]["sha256"][:2], "50")
            self.assertEqual(len(evidence_sha), 64)

    def test_no_oracle_even_with_a_passing_pipeline_is_partial(self):
        with tempfile.TemporaryDirectory() as tmp:
            info = self._setup(tmp)
            report = run_batch([info["root"]], info["out"])
            record = report["games"][0]
            self.assertEqual(record["pipeline"]["status"], "ok")
            self.assertEqual(record["verdict"], cs.PARTIAL, record["reasons"])
            self.assertTrue(any("no supplied original-Windows oracle" in r
                                for r in record["reasons"]))


