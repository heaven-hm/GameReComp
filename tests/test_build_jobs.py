"""Issue #26: adaptive --parallel must not fill the volume or exhaust RAM mid-build.

The policies are deterministic given (requested jobs, generated bytes, free
disk, available RAM), so they are tested by stubbing os.statvfs and the memory
probe instead of filling a real disk or allocating real RAM. The generated-tree
gitignore check shells out to `git check-ignore` on paths that do not exist, so
it needs no multi-GB fixture either.
"""
import os
import subprocess
import sys
import unittest
from pathlib import Path
from unittest import mock

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tools.autorecomp import pipeline as _pipeline  # noqa: E402
from tools.autorecomp.pipeline import (  # noqa: E402
    BUILD_FREE_MARGIN, BUILD_MEM_FLOOR,
    available_memory_bytes, effective_build_jobs, memory_limited_jobs,
)


class _Stat:
    def __init__(self, free_bytes):
        self.f_bavail = free_bytes // 4096
        self.f_frsize = 4096


def _with_free(free_bytes):
    return mock.patch.object(os, "statvfs", return_value=_Stat(free_bytes))


def _with_memory(available_bytes):
    return mock.patch.object(_pipeline, "available_memory_bytes",
                             return_value=available_bytes)


class BuildJobsTests(unittest.TestCase):
    def setUp(self):
        # Disk-focused tests must stay deterministic regardless of the host's
        # actual RAM: hold the memory probe at "ample" for this class only.
        patcher = _with_memory(1 << 40)
        patcher.start()
        self.addCleanup(patcher.stop)

    def test_ample_disk_keeps_requested_jobs(self):
        with _with_free(100 << 30):
            self.assertEqual(effective_build_jobs(8, 500 << 20), 8)

    def test_low_disk_reduces_jobs(self):
        # 1.5 GiB free, 500 MiB of generated C: eight concurrent objects cannot
        # fit alongside a 1 GiB margin, but some parallelism still can.
        with _with_free((3 << 30) // 2):
            jobs = effective_build_jobs(8, 500 << 20)
        self.assertGreaterEqual(jobs, 1)
        self.assertLess(jobs, 8)

    def test_critical_disk_uses_one_job(self):
        with _with_free(100 << 20):
            self.assertEqual(effective_build_jobs(16, 500 << 20), 1)

    def test_zero_or_one_request_never_parallel(self):
        with _with_free(100 << 30):
            self.assertEqual(effective_build_jobs(1, 0), 1)
            self.assertEqual(effective_build_jobs(0, 500 << 20), 1)

    def test_statvfs_failure_keeps_requested_jobs(self):
        with mock.patch.object(os, "statvfs", side_effect=OSError("no statvfs")):
            self.assertEqual(effective_build_jobs(6, 500 << 20), 6)

    def test_margin_is_respected(self):
        # Free space below the margin plus the minimum floor collapses to one
        # job even for a small source tree.
        with _with_free(BUILD_FREE_MARGIN + (128 << 20)):
            self.assertEqual(effective_build_jobs(8, 10 << 20), 1)


class MemoryJobsTests(unittest.TestCase):
    def setUp(self):
        # Disk-focused tests hold the memory probe ample; do the converse here
        # so a nearly full host volume cannot reduce the requested jobs and
        # mask the memory policy under test.
        patcher = _with_free(100 << 30)
        patcher.start()
        self.addCleanup(patcher.stop)

    def test_ample_memory_keeps_requested_jobs(self):
        with _with_memory(64 << 30):
            self.assertEqual(effective_build_jobs(8, 500 << 20), 8)

    def test_low_memory_reduces_jobs(self):
        # 4 GiB available, 8 requested: 1 GiB reserved + 1 GiB/job => 3 jobs.
        with _with_memory(4 << 30):
            self.assertEqual(effective_build_jobs(8, 500 << 20), 3)

    def test_below_floor_collapses_to_one_job(self):
        with _with_memory(512 << 20):
            self.assertEqual(effective_build_jobs(16, 500 << 20), 1)
        self.assertEqual(memory_limited_jobs(8, BUILD_MEM_FLOOR), 1)

    def test_unmeasured_memory_keeps_requested_jobs(self):
        with _with_memory(None):
            self.assertEqual(effective_build_jobs(6, 500 << 20), 6)
        self.assertEqual(memory_limited_jobs(8, None), 8)

    def test_explicit_measurement_overrides_probe(self):
        # A caller-supplied measurement wins over the module-level probe.
        with _with_memory(64 << 30):
            self.assertEqual(
                effective_build_jobs(8, 500 << 20, available_bytes=2 << 30), 1)

    def test_tighter_of_disk_and_memory_caps_wins(self):
        with _with_free(100 << 30), _with_memory(4 << 30):
            # Disk would allow 8, memory allows only 3.
            self.assertEqual(effective_build_jobs(8, 500 << 20), 3)
        with _with_free((3 << 30) // 2), _with_memory(64 << 30):
            # Memory would allow 8, disk reduces the count.
            self.assertLess(effective_build_jobs(8, 500 << 20), 8)

    def test_memory_limited_jobs_is_pure(self):
        self.assertEqual(memory_limited_jobs(1, 1), 1)
        self.assertEqual(memory_limited_jobs(0, 64 << 30), 1)
        self.assertEqual(memory_limited_jobs(8, 8 << 30), 7)

    def test_linux_meminfo_parser(self):
        meminfo = "MemTotal: 16384 kB\nMemAvailable: 7777777 kB\nSwapFree: 0 kB\n"
        with mock.patch.object(_pipeline.sys, "platform", "linux"), \
                mock.patch("builtins.open", mock.mock_open(read_data=meminfo)):
            self.assertEqual(available_memory_bytes(), 7777777 * 1024)

    def test_unmeasurable_memory_returns_none(self):
        with mock.patch.object(_pipeline.sys, "platform", "linux"), \
                mock.patch("builtins.open", side_effect=OSError("no proc")), \
                mock.patch.object(_pipeline.os, "sysconf",
                                  side_effect=ValueError("no sysconf")):
            self.assertIsNone(available_memory_bytes())


class GeneratedTreeGitignoreTests(unittest.TestCase):
    """Generated project trees are multi-GB; none may be committed."""

    PATHS = (
        "projects/ikachan/src/main.c",
        "test-results/game-matrix/execution/projects/foo/src/main.c",
        "reports/oracle-sweep/tetris-project/src/main.c",
        "out/custom-root/foo-project/src/main.c",
        "foo-project/src/main.c",
    )

    def test_generated_project_trees_are_ignored(self):
        for rel in self.PATHS:
            try:
                proc = subprocess.run(
                    ["git", "check-ignore", "--quiet", rel],
                    cwd=str(ROOT), capture_output=True, text=True)
            except FileNotFoundError:
                self.skipTest("git not available")
            self.assertEqual(proc.returncode, 0,
                             f"generated tree not ignored: {rel}")


if __name__ == "__main__":
    unittest.main()
