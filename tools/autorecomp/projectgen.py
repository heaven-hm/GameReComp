"""Generate a self-contained buildable project from translated sources.

The project copies the win32hle runtime and recomp_types.h beside the generated
C files, so the delivered tree compiles with nothing from this repository but a
C compiler, CMake, SDL2 and (optionally) FFmpeg.
"""

import json
import os
import shutil
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
RUNTIME_ROOT = REPO_ROOT / "runtime"
WIN32HLE = RUNTIME_ROOT / "win32hle"
RECOMP32 = RUNTIME_ROOT / "recomp32"

MAIN_C = """\
/* Entry point for the rebuilt game.
 * recomp_host_main() boots the original PE named by argv[1] - a fresh copy of
 * the game executable, not the rebuilt one - then calls the recompiled entry
 * point and runs the guest until it returns.
 *
 * Strict binding is the default: an unresolved import fails the boot. Setting
 * RECOMP_PERMISSIVE=1 binds unresolved imports to the runtime's self-naming
 * stub instead, so the guest runs until it actually calls one and then aborts
 * naming that import. That is the bring-up loop for a new title, and what
 * tools/autorecomp/diagnose.py drives. It is a diagnostic, not a way to run a
 * game: the stub cannot return, so the run always stops at the first
 * unimplemented import.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "host.h"

static int permissive_requested(void) {
    const char *v = getenv("RECOMP_PERMISSIVE");
    return v != NULL && v[0] != '\\0' && strcmp(v, "0") != 0;
}

int main(int argc, char **argv) {
    if (!permissive_requested()) return recomp_host_main(argc, argv);
    if (argc < 2) {
        fprintf(stderr, "usage: %s <image.exe> [args...]\\n", argv[0]);
        return 64;
    }
    recomp_host_init();
    int rc = recomp_host_boot_permissive(argv[1]);
    if (rc) return rc;
    return (int)recomp_host_run();
}
"""

CMAKE = """\
# Generated by RevEng-Studio autorecomp. Build:
#   cmake -S . -B build && cmake --build build -j
cmake_minimum_required(VERSION 3.16)
project(@NAME@ C)

set(CMAKE_C_STANDARD 11)
if(NOT CMAKE_BUILD_TYPE)
  set(CMAKE_BUILD_TYPE Release)
endif()

find_package(PkgConfig REQUIRED)
pkg_check_modules(SDL2 REQUIRED IMPORTED_TARGET sdl2 SDL2_ttf)
pkg_check_modules(FFMPEG IMPORTED_TARGET libavformat libavcodec libavutil libswresample)

file(GLOB RECOMP_SOURCES CONFIGURE_DEPENDS "${CMAKE_CURRENT_SOURCE_DIR}/src/recomp/gen/recomp_*.c")
file(GLOB RUNTIME_SOURCES CONFIGURE_DEPENDS "${CMAKE_CURRENT_SOURCE_DIR}/src/runtime/win32hle/*.c")

add_executable(@NAME@
  src/main.c
  ${RECOMP_SOURCES}
  src/recomp/gen/recomp_dispatch.c
  ${RUNTIME_SOURCES}
)

target_include_directories(@NAME@ PRIVATE
  src/recomp/gen
  src/runtime/recomp32
  src/runtime/win32hle
)

# Generated code is machine-shaped register C; the warnings it would raise are
# not actionable and would bury the runtime's.
target_compile_options(@NAME@ PRIVATE -w)
target_link_libraries(@NAME@ PRIVATE PkgConfig::SDL2 m pthread)

if(FFMPEG_FOUND)
  target_compile_definitions(@NAME@ PRIVATE HLE_WITH_FFMPEG)
  target_link_libraries(@NAME@ PRIVATE PkgConfig::FFMPEG)
else()
  message(WARNING "FFmpeg not found: Bink/MSS movie and audio decoding disabled")
endif()
"""

README = """\
# @NAME@

Rebuilt from `@EXE@` by RevEng-Studio autorecomp.

- Source: `src/recomp/gen/recomp_*.c` (one function per original address,
  `sub_XXXXXXXX`; register-transfer C, provenance `LOW_LEVEL_FALLBACK`)
- Runtime: `src/runtime/win32hle/` (pinned copy), `src/runtime/recomp32/recomp_types.h`
- Build: `cmake -S . -B build && cmake --build build -j`
- Run: `./build/@NAME@ /path/to/@EXE@` (the original executable supplies the
  program image and data; it is never modified)

Build dependencies: a C compiler, CMake >= 3.16, SDL2 + SDL2_ttf development
packages, pthreads. FFmpeg (libavformat/libavcodec/libavutil/libswresample) is
optional and only enables Bink/MSS movie and audio decoding.

This project does not contain or redistribute the original game's assets.
"""


def _copy_runtime(project_dir: Path) -> dict:
    """Copy the runtime sources the generated project needs to build."""
    win_dst = project_dir / "src" / "runtime" / "win32hle"
    rec_dst = project_dir / "src" / "runtime" / "recomp32"
    win_dst.mkdir(parents=True, exist_ok=True)
    rec_dst.mkdir(parents=True, exist_ok=True)

    runtime_files = []
    for path in sorted(WIN32HLE.iterdir()):
        if path.suffix not in (".c", ".h"):
            continue
        if path.name.endswith("_selftest.c"):
            continue
        shutil.copy2(path, win_dst / path.name)
        runtime_files.append(f"src/runtime/win32hle/{path.name}")

    for name in ("recomp_types.h",):
        shutil.copy2(RECOMP32 / name, rec_dst / name)
        runtime_files.append(f"src/runtime/recomp32/{name}")
    return {"files": runtime_files}


def write_project(project_dir, name, exe_name, pe_info, extra=None) -> dict:
    """Write main.c, CMakeLists.txt, README and project.json.

    pe_info: dict of inspect-stage metadata for project.json provenance.
    Returns a small summary dict.
    """
    project_dir = Path(project_dir)
    project_dir.mkdir(parents=True, exist_ok=True)
    (project_dir / "src").mkdir(exist_ok=True)

    runtime = _copy_runtime(project_dir)

    (project_dir / "src" / "main.c").write_text(MAIN_C)
    (project_dir / "CMakeLists.txt").write_text(CMAKE.replace("@NAME@", name))
    (project_dir / "README.md").write_text(
        README.replace("@NAME@", name).replace("@EXE@", exe_name))

    record = {
        "schema": 1,
        "name": name,
        "original_executable": exe_name,
        "generator": "reveng-studio autorecomp",
        "backend": "pcrecomp (tools/lift, tools/disasm, tools/pe)",
        "runtime": "win32hle",
        "target": {
            "os": "host",
            "arch": "host",
            "note": "built and run on the machine that generated it",
        },
        "pe": pe_info,
        "runtime_files": runtime["files"],
    }
    if extra:
        record.update(extra)
    (project_dir / "project.json").write_text(json.dumps(record, indent=2) + "\n")
    return record


def executable_name(pe_path) -> str:
    """A CMake-safe target name from the original executable's stem."""
    stem = Path(pe_path).stem
    safe = "".join(c if c.isalnum() or c == "_" else "_" for c in stem)
    if not safe or safe[0].isdigit():
        safe = "game_" + safe
    return safe


def default_project_dir(pe_path, base="projects") -> Path:
    return Path(base) / executable_name(pe_path)
