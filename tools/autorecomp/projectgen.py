"""Generate a self-contained buildable project from translated sources.

The project copies the win32hle runtime and recomp_types.h beside the generated
C files, so the delivered tree compiles with nothing from this repository but a
C compiler, CMake, SDL2 and (optionally) FFmpeg.
"""

import json
from contextlib import contextmanager
import errno
import os
import shutil
import stat
import subprocess
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
RUNTIME_ROOT = REPO_ROOT / "runtime"
WIN32HLE = RUNTIME_ROOT / "win32hle"
RECOMP32 = RUNTIME_ROOT / "recomp32"


def _validate_existing_license(path: Path) -> None:
    try:
        license_fd = os.open(path, os.O_RDONLY | getattr(os, "O_NONBLOCK", 0))
        try:
            if not stat.S_ISREG(os.fstat(license_fd).st_mode):
                raise RuntimeError(f"Existing project license is not a regular file: {path}")
        finally:
            os.close(license_fd)
    except OSError as exc:
        raise RuntimeError(f"Existing project license is not readable: {path}: {exc}") from exc


@contextmanager
def _project_license_lock(project_dir: Path):
    lock_fd = os.open(project_dir / ".LICENSE.lock", os.O_RDWR | os.O_CREAT, 0o600)
    try:
        if os.name == "nt":
            import msvcrt
            if os.fstat(lock_fd).st_size == 0:
                os.write(lock_fd, b"\0")
            os.lseek(lock_fd, 0, os.SEEK_SET)
            msvcrt.locking(lock_fd, msvcrt.LK_LOCK, 1)
        else:
            import fcntl
            fcntl.flock(lock_fd, fcntl.LOCK_EX)
        yield
    finally:
        if os.name == "nt":
            import msvcrt
            os.lseek(lock_fd, 0, os.SEEK_SET)
            msvcrt.locking(lock_fd, msvcrt.LK_UNLCK, 1)
        else:
            import fcntl
            fcntl.flock(lock_fd, fcntl.LOCK_UN)
        os.close(lock_fd)


def _fsync_directory(path: Path) -> None:
    if os.name == "nt":
        return
    fd = os.open(path, os.O_RDONLY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)

MAIN_C = """\
/* Entry point for the rebuilt game.
 * recomp_host_main() maps the image and runs the recompiled entry point until
 * the guest exits. The image is embedded at build time, so the original
 * Windows executable is NOT needed at run time. When the game needs its own
 * data files, pass the game's directory as the first argument; otherwise just
 * run it.
 *
 * Strict binding is the default: an unresolved import fails the boot. Setting
 * RECOMP_PERMISSIVE=1 binds unresolved imports to the runtime's self-naming
 * stub instead, so the guest runs until it actually calls one and then aborts
 * naming that import. That is the bring-up loop for a new title, and what
 * tools/autorecomp/diagnose.py drives. It is a diagnostic, not a way to run a
 * game: the stub cannot return, so the run always stops at the first
 * unimplemented import.
 *
 * RECOMP_TRACE=1 logs every import dispatch; without it a crash in lifted code
 * gives no clue which shim ran last.
 */
#include "host.h"

int main(int argc, char **argv) {
    return recomp_host_main(argc, argv);
}
"""

IMAGE_ASM = """\
/* Auto-generated: the original PE, embedded so the rebuilt binary runs without
 * it. .incbin reads the copy beside this file, by absolute path (the assembler
 * runs from the build directory). The symbol carries the platform's C prefix. */
#if defined(__APPLE__)
#define SYM(x) _##x
    .section __DATA,__const
#else
#define SYM(x) x
    .section .rodata
#endif
    .p2align 4
    .globl SYM(recomp_original_image)
SYM(recomp_original_image):
    .incbin "@BLOB@"
"""

CMAKE = """\
# Generated by GameReComp autorecomp. Build:
#   cmake -S . -B build && cmake --build build -j
cmake_minimum_required(VERSION 3.16)
project(@NAME@ C)
enable_language(ASM)

set(CMAKE_C_STANDARD 11)
if(NOT CMAKE_BUILD_TYPE)
  set(CMAKE_BUILD_TYPE Release)
endif()

find_package(PkgConfig REQUIRED)
pkg_check_modules(SDL2 REQUIRED IMPORTED_TARGET sdl2 SDL2_ttf)
pkg_check_modules(FFMPEG IMPORTED_TARGET libavformat libavcodec libavutil libswresample)

# gl32.c dlopen()s the host GLU by its usual names. On Linux that is libdl; on
# macOS and the BSDs dlopen lives in libc, and linking -ldl there fails.
include(CheckIncludeFile)
if(UNIX AND NOT APPLE)
  find_library(DL_LIBRARY dl)
endif()

file(GLOB RECOMP_SOURCES CONFIGURE_DEPENDS "${CMAKE_CURRENT_SOURCE_DIR}/src/recomp/gen/recomp_*.c")
file(GLOB RUNTIME_SOURCES CONFIGURE_DEPENDS "${CMAKE_CURRENT_SOURCE_DIR}/src/runtime/win32hle/*.c")

# The embedded images (the original PE, and any bundled DLLs), when this
# project was built to run without the original executable or its DLLs.
if(EXISTS "${CMAKE_CURRENT_SOURCE_DIR}/src/recomp/gen/recomp_image.S")
  list(APPEND RECOMP_IMAGE_ASM src/recomp/gen/recomp_image.S)
endif()
if(EXISTS "${CMAKE_CURRENT_SOURCE_DIR}/src/recomp/gen/recomp_companion_images.S")
  list(APPEND RECOMP_IMAGE_ASM src/recomp/gen/recomp_companion_images.S)
endif()

add_executable(@NAME@
  src/main.c
  ${RECOMP_SOURCES}
  ${RECOMP_IMAGE_ASM}
  src/recomp/gen/recomp_dispatch.c
  ${RUNTIME_SOURCES}
)

target_include_directories(@NAME@ PRIVATE
  src/recomp/gen
  src/runtime/recomp32
  src/runtime/win32hle
  src/highlevel
)

# High-level source units: typed functions plus the generated adapters that
# expose them through the guest ABI. Compiled into this executable alongside
# the mechanical bodies, which stay under their sub_XXXXXXXX__lowlevel names.
file(GLOB HIGHLEVEL_SOURCES CONFIGURE_DEPENDS
  "${CMAKE_CURRENT_SOURCE_DIR}/src/highlevel/*.c")
if(HIGHLEVEL_SOURCES)
  target_sources(@NAME@ PRIVATE ${HIGHLEVEL_SOURCES})
endif()

# Generated code is machine-shaped register C; the warnings it would raise are
# not actionable and would bury the runtime's.
target_compile_options(@NAME@ PRIVATE -w)
target_link_libraries(@NAME@ PRIVATE PkgConfig::SDL2 m pthread)
if(DL_LIBRARY)
  target_link_libraries(@NAME@ PRIVATE ${DL_LIBRARY})
endif()

if(FFMPEG_FOUND)
  target_compile_definitions(@NAME@ PRIVATE HLE_WITH_FFMPEG)
  target_link_libraries(@NAME@ PRIVATE PkgConfig::FFMPEG)
else()
  message(WARNING "FFmpeg not found: Bink/MSS movie and audio decoding disabled")
endif()
"""

README = """\
# @NAME@

Rebuilt from `@EXE@` by GameReComp autorecomp.

- Source: `src/recomp/gen/recomp_*.c` (one function per original address,
  `sub_XXXXXXXX`; register-transfer C, provenance `LOW_LEVEL_FALLBACK`)
- High-level source: `src/highlevel/` (typed C plus the generated ABI adapters;
  present only when a module replaced a function, and the mechanical body of a
  replaced function stays compiled as `sub_XXXXXXXX__lowlevel`)
- Runtime: `src/runtime/win32hle/` (pinned copy), `src/runtime/recomp32/recomp_types.h`
- Build: `cmake -S . -B build && cmake --build build -j`
- Run: `./build/@NAME@` (the program image from `@EXE@` and any bundled DLLs
  are embedded in the rebuilt binary, so the original executable is not
  needed at run time; pass `[assets-dir]` or set `RECOMP_ASSETS_DIR` if the
  program reads external data files)

Build dependencies: a C compiler, CMake >= 3.16, SDL2 + SDL2_ttf development
packages, pthreads. FFmpeg (libavformat/libavcodec/libavutil/libswresample) is
optional and only enables Bink/MSS movie and audio decoding.

This project does not contain or redistribute the original game's assets.
"""


def check_runtime_sources(cc=None, extra_cflags=()):
    """Syntax-check the runtime sources a generated project will build.

    The runtime is copied into every project, so a single broken file there
    fails the build of every game with an error that reads like broken
    *generated* code -- and it fails it after the expensive translate stage has
    already written hundreds of megabytes. Checking the runtime first turns a
    confusing late failure into a clear early one.

    Returns (ok, [messages]). A missing compiler is not a failure: the check is
    a convenience, and the real build reports the truth either way.
    """
    cc = cc or os.environ.get("CC") or "cc"
    if shutil.which(cc) is None:
        return True, [f"{cc} not found; runtime preflight skipped"]
    cflags = ["-fsyntax-only"]
    for pkg in (("sdl2", "SDL2_ttf"),):
        try:
            out = subprocess.run(["pkg-config", "--cflags", *pkg],
                                 capture_output=True, text=True, timeout=30)
            if out.returncode == 0:
                cflags.extend(out.stdout.split())
        except (OSError, subprocess.SubprocessError):
            pass
    cflags.extend(extra_cflags)
    cflags.extend(["-I", str(RECOMP32), "-I", str(WIN32HLE)])

    failures = []
    for path in sorted(WIN32HLE.glob("*.c")):
        if path.name.endswith("_selftest.c"):
            continue
        try:
            proc = subprocess.run([cc, *cflags, str(path)],
                                  capture_output=True, text=True, timeout=120)
        except (OSError, subprocess.SubprocessError) as exc:
            return True, [f"runtime preflight skipped ({exc})"]
        if proc.returncode != 0:
            first = next((ln for ln in proc.stderr.splitlines() if "error:" in ln),
                         proc.stderr.strip().splitlines()[0] if proc.stderr.strip() else "?")
            failures.append(f"{path.name}: {first.strip()}")
    return (not failures), failures


def _copy_runtime(project_dir: Path) -> dict:
    """Copy the runtime sources the generated project needs to build."""
    win_dst = project_dir / "src" / "runtime" / "win32hle"
    rec_dst = project_dir / "src" / "runtime" / "recomp32"
    win_dst.mkdir(parents=True, exist_ok=True)
    rec_dst.mkdir(parents=True, exist_ok=True)

    # MIRROR, do not merely add. A runtime file that was removed or renamed
    # upstream stayed in every generated project and kept being compiled: a
    # deleted clock.c lived on in projects/*/src/runtime/win32hle/, where it
    # collided with the file that replaced it. What is delivered must be what
    # the runtime directory holds, and nothing else.
    wanted = {p.name for p in WIN32HLE.iterdir()
              if p.suffix in (".c", ".h") and not p.name.endswith("_selftest.c")}
    for stale in sorted(win_dst.iterdir()):
        if stale.is_file() and stale.name not in wanted:
            stale.unlink()

    runtime_files = []
    for path in sorted(WIN32HLE.iterdir()):
        if path.suffix not in (".c", ".h"):
            continue
        if path.name.endswith("_selftest.c"):
            continue
        dst = win_dst / path.name
        # copy2 preserves the source mtime, and make decides by mtime: a
        # runtime file that changed but kept an older timestamp than the last
        # build was silently NOT recompiled, so a project could link a stale
        # runtime and a fix would appear not to work. Measured: a new
        # RECOMP_CALL_CAP had no effect on a rebuilt project for exactly this
        # reason. Copy the content, then stamp it now.
        shutil.copyfile(path, dst)
        os.utime(dst, None)
        runtime_files.append(f"src/runtime/win32hle/{path.name}")

    for name in ("recomp_types.h",):
        dst = rec_dst / name
        shutil.copyfile(RECOMP32 / name, dst)
        os.utime(dst, None)
        runtime_files.append(f"src/runtime/recomp32/{name}")
    return {"files": runtime_files}


def write_project(project_dir, name, exe_name, pe_info, extra=None,
                  highlevel_modules=None, embed_image=None) -> dict:
    """Write main.c, CMakeLists.txt, README and project.json.

    pe_info: dict of inspect-stage metadata for project.json provenance.
    highlevel_modules: modules from tools/autorecomp/highlevel.py. Their typed
        sources are copied in, the adapters are generated beside them, and the
        dispatch table (written by the translator) points at the adapters. The
        mechanical bodies stay compiled under their __lowlevel names.
    embed_image: path to the original PE to embed, so the rebuilt binary runs
        without it. None leaves the file-based boot (needs the original exe).
    Returns a small summary dict.
    """
    project_dir = Path(project_dir)
    project_dir.mkdir(parents=True, exist_ok=True)
    (project_dir / "src").mkdir(exist_ok=True)
    source_license = REPO_ROOT / "LICENSE"
    output_license = project_dir / "LICENSE"
    incomplete_marker = project_dir / ".LICENSE.incomplete"
    with _project_license_lock(project_dir):
        if os.path.lexists(incomplete_marker):
            raise RuntimeError(
                f"A prior license copy was interrupted in {project_dir}; inspect and remove {incomplete_marker} and any incomplete LICENSE before retrying"
            )
        if os.path.lexists(output_license):
            _validate_existing_license(output_license)
        else:
            source_mode = stat.S_IMODE(source_license.stat().st_mode)
            fd, temporary_license = tempfile.mkstemp(prefix=".LICENSE.", dir=project_dir)
            try:
                with os.fdopen(fd, "wb") as dst, open(source_license, "rb") as src:
                    shutil.copyfileobj(src, dst)
                    dst.flush()
                    os.fsync(dst.fileno())
                with open(temporary_license, "rb") as staged_source:
                    os.chmod(temporary_license, source_mode)
                    try:
                        os.link(temporary_license, output_license)
                    except FileExistsError:
                        _validate_existing_license(output_license)
                    except OSError as exc:
                        unsupported_link = {
                            errno.EPERM, errno.EXDEV, errno.EINVAL,
                            getattr(errno, "EOPNOTSUPP", errno.EPERM),
                            getattr(errno, "ENOTSUP", errno.EPERM),
                            getattr(errno, "ENOSYS", errno.EPERM),
                        }
                        if exc.errno not in unsupported_link:
                            raise
                        marker_fd = os.open(
                            incomplete_marker,
                            os.O_WRONLY | os.O_CREAT | os.O_EXCL,
                            0o600,
                        )
                        with os.fdopen(marker_fd, "w", encoding="ascii") as marker:
                            marker.write("GameReComp LICENSE publication in progress\n")
                            marker.flush()
                            os.fsync(marker.fileno())
                        _fsync_directory(project_dir)
                        try:
                            output_fd = os.open(
                                output_license,
                                os.O_WRONLY | os.O_CREAT | os.O_EXCL,
                                0o600,
                            )
                        except FileExistsError:
                            incomplete_marker.unlink()
                            _fsync_directory(project_dir)
                            _validate_existing_license(output_license)
                        except OSError:
                            incomplete_marker.unlink(missing_ok=True)
                            _fsync_directory(project_dir)
                            raise
                        else:
                            with os.fdopen(output_fd, "wb") as dst:
                                staged_source.seek(0)
                                shutil.copyfileobj(staged_source, dst)
                                dst.flush()
                                os.fsync(dst.fileno())
                                if hasattr(os, "fchmod"):
                                    os.fchmod(dst.fileno(), source_mode)
                            incomplete_marker.unlink()
                            _fsync_directory(project_dir)
            finally:
                try:
                    os.unlink(temporary_license)
                except FileNotFoundError:
                    pass

    runtime = _copy_runtime(project_dir)

    highlevel_files = []
    if highlevel_modules:
        from . import highlevel as _highlevel
        hl_src = project_dir / "src" / "highlevel"
        hl_src.mkdir(parents=True, exist_ok=True)
        for module in highlevel_modules:
            for source in module["sources"]:
                dst = hl_src / source.name
                shutil.copyfile(source, dst)
                os.utime(dst, None)          # see the mtime note in _copy_runtime
                highlevel_files.append(f"src/highlevel/{source.name}")
        # The adapters and the declarations are generated, never authored: the
        # guest ABI marshalling lives in exactly one place.
        for written in _highlevel.emit_unit(highlevel_modules, hl_src):
            highlevel_files.append(f"src/highlevel/{written.name}")
        (hl_src / "highlevel_impl.h").write_text(
            _highlevel.header_source(highlevel_modules))
        highlevel_files.append("src/highlevel/highlevel_impl.h")

    (project_dir / "src" / "main.c").write_text(MAIN_C)
    (project_dir / "CMakeLists.txt").write_text(CMAKE.replace("@NAME@", name))
    (project_dir / "README.md").write_text(
        README.replace("@NAME@", name).replace("@EXE@", exe_name))

    image_files = []
    if embed_image:
        # Embed the original PE so the rebuilt binary does not need it at run
        # time. The bytes go in a .bin (compiled via .incbin, so a large image
        # does not become megabytes of C source), and the base name in a tiny
        # C file for the guest's own command line.
        gen = project_dir / "src" / "recomp" / "gen"
        gen.mkdir(parents=True, exist_ok=True)
        blob = gen / "recomp_image.bin"
        blob.write_bytes(Path(embed_image).read_bytes())
        safe = exe_name.replace('\\', '\\\\').replace('"', '\\"')
        (gen / "recomp_image.c").write_text(
            "/* Auto-generated: the original executable's base name and size, and the\n"
            " * flag that says the image is embedded. The bytes are recomp_image.S. */\n"
            "const int recomp_has_embedded_image = 1;\n"
            f"const unsigned long recomp_original_image_size = {blob.stat().st_size}UL;\n"
            f'const char recomp_original_name[] = "{safe}";\n')
        (gen / "recomp_image.S").write_text(
            IMAGE_ASM.replace("@BLOB@", str(blob.resolve())))
        image_files = ["src/recomp/gen/recomp_image.bin",
                       "src/recomp/gen/recomp_image.c",
                       "src/recomp/gen/recomp_image.S"]

    record = {
        "schema": 1,
        "name": name,
        "original_executable": exe_name,
        "generator": "GameReComp autorecomp",
        "backend": "pcrecomp (tools/lift, tools/disasm, tools/pe)",
        "runtime": "win32hle",
        "target": {
            "os": "host",
            "arch": "host",
            "note": "built and run on the machine that generated it",
        },
        "pe": pe_info,
        "runtime_files": runtime["files"],
        "highlevel_files": highlevel_files,
        "image_files": image_files,
        "image_embedded": bool(embed_image),
    }
    if extra:
        record.update(extra)
    (project_dir / "project.json").write_text(json.dumps(record, indent=2) + "\n")
    return record


def executable_name(pe_path) -> str:
    """A CMake-safe target name from the original executable's stem."""
    stem = Path(pe_path).stem
    safe = "".join(c if c.isalnum() or c == "_" else "_" for c in stem)
    if not safe or safe[0].isdigit():
        safe = "game_" + safe
    return safe


def default_project_dir(pe_path, base="projects") -> Path:
    return Path(base) / executable_name(pe_path)
