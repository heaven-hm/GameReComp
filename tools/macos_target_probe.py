#!/usr/bin/env python3
"""macos_target_probe.py - fail-closed macOS host/target architecture probe.

Why this exists
---------------
On this repository the only measured native host is macOS arm64. A sibling
host architecture (x86_64) can be *cross-compiled* here with the Command Line
Tools SDK, and on some arm64 Macs the resulting binary can also be *executed* -
but through Rosetta 2 binary translation, which is not native x86_64 execution.
Treating "the binary ran" as "the x86_64 target works natively" would be a
claim this machine cannot support. This tool reports the three distinct
capabilities separately:

  * build for an architecture (Mach-O cputype verified from the header itself),
  * run natively on the host (verified with sysctl.proc_translated == 0),
  * run translated (sysctl.proc_translated == 1, i.e. Rosetta 2).

Every capability is fail-closed: if a command is missing, a compile fails, or
a Mach-O header cannot be parsed, that capability is reported as *not proven*
with the reason, never as true. No capability is inferred from the SDK's
advertised architecture list alone - a real object/executable is built and its
header is read back.

Usage
-----
  python3 tools/macos_target_probe.py                  # human-readable report
  python3 tools/macos_target_probe.py --json            # machine-readable report
  python3 tools/macos_target_probe.py --require-native x86_64
      # exits non-zero: native x86_64 is NOT proven on an arm64 host (Rosetta
      # translation does not count). This is the fail-closed gate.
  python3 tools/macos_target_probe.py --require-build x86_64
      # exits 0 here: cross-compilation to x86_64-apple-macos11 is proven.

The report contains the exact argv of every command run, so a result can be
reproduced or audited without trusting the tool's summary.
"""

import argparse
import json
import os
import platform
import shutil
import struct
import subprocess
import sys
import tempfile

SCHEMA = "macos-target-probe/1"

# mach/machine.h CPU_TYPE_* values. Shifts are deliberate: the low byte is the
# architecture and the high bit marks a 64-bit ABI.
CPU_TYPE_I386 = 7
CPU_TYPE_X86_64 = 0x01000007
CPU_TYPE_ARM = 12
CPU_TYPE_ARM64 = 0x0100000C
CPU_TYPE_ARM64_32 = 0x0200000C
CPU_TYPE_NAME = {
    CPU_TYPE_I386: "i386",
    CPU_TYPE_X86_64: "x86_64",
    CPU_TYPE_ARM: "arm",
    CPU_TYPE_ARM64: "arm64",
    CPU_TYPE_ARM64_32: "arm64_32",
}

TARGETS = {
    "arm64": "arm64-apple-macos{ver}",
    "x86_64": "x86_64-apple-macos{ver}",
}
EXPECTED_CPU = {"arm64": CPU_TYPE_ARM64, "x86_64": CPU_TYPE_X86_64}

ROSETTA_PATHS = (
    "/Library/Apple/usr/libexec/oah/libRosettaRuntime",
    "/usr/libexec/rosetta/oahd",
    "/usr/libexec/rosetta/runtime",
)

# A deliberately tiny but real executable. sysctlbyname is the only reliable
# way to distinguish native execution from Rosetta translation from inside the
# process: uname() reports "arm64" in both cases when the binary is translated.
PROBE_SOURCE = r"""/* generated by tools/macos_target_probe.py - do not edit */
#include <stdio.h>
#include <sys/sysctl.h>
int main(void) {
    int translated = -1;
    size_t n = sizeof(translated);
    if (sysctlbyname("sysctl.proc_translated", &translated, &n, NULL, 0) != 0)
        translated = -1;
    printf("PROBE_OK=1\nPROC_TRANSLATED=%d\n", translated);
    return 0;
}
"""


class MachOError(ValueError):
    """The bytes are not a Mach-O whose header can be trusted."""


class CommandError(RuntimeError):
    """A probe command could not be completed; the capability stays unproven."""


def run(argv, cwd=None, timeout=60):
    """Run argv without a shell. Returns a record with exact argv and output.

    Fail-closed: a missing binary, timeout, or non-zero status is recorded, not
    raised. The caller decides what the status proves.
    """
    rec = {"argv": list(argv), "cwd": cwd, "rc": None, "stdout": "", "stderr": ""}
    try:
        p = subprocess.run(argv, cwd=cwd, capture_output=True, text=True,
                           errors="replace", timeout=timeout)
    except FileNotFoundError as e:
        rec["stderr"] = "not found: %s" % e
        return rec
    except subprocess.TimeoutExpired as e:
        rec["stderr"] = "timeout after %ss" % timeout
        return rec
    rec["rc"] = p.returncode
    rec["stdout"] = p.stdout.strip()
    rec["stderr"] = p.stderr.strip()
    return rec


def parse_macho(data):
    """Return {cputype, arch, filetype, is64, fat} for a Mach-O, fail-closed.

    Handles thin 32/64-bit and fat 32/64-bit headers in either byte order.
    Raises MachOError on anything it cannot read: a capability built on an
    unparsable header is never reported as proven.
    """
    if len(data) < 4:
        raise MachOError("too short for a Mach-O magic")
    magic = bytes(data[:4])
    thin = {
        b"\xcf\xfa\xed\xfe": ("<", True),
        b"\xfe\xed\xfa\xcf": (">", True),
        b"\xce\xfa\xed\xfe": ("<", False),
        b"\xfe\xed\xfa\xce": (">", False),
    }
    fat = {
        b"\xca\xfe\xba\xbe": (">", False),   # FAT_MAGIC
        b"\xbe\xba\xfe\xca": ("<", False),   # FAT_CIGAM
        b"\xca\xfe\xba\xbf": (">", True),    # FAT_MAGIC_64
        b"\xbf\xba\xfe\xca": ("<", True),    # FAT_CIGAM_64
    }
    if magic in fat:
        endian, is64 = fat[magic]
        if len(data) < 8:
            raise MachOError("truncated fat header")
        n = struct.unpack_from(endian + "I", data, 4)[0]
        entry = 32 if is64 else 20
        if n < 1 or n > 4096 or len(data) < 8 + n * entry:
            raise MachOError("bad fat arch count %d" % n)
        cputypes = [struct.unpack_from(endian + "I", data, 8 + i * entry)[0]
                    for i in range(n)]
        return {"cputype": cputypes[0], "cputypes": cputypes,
                "arch": CPU_TYPE_NAME.get(cputypes[0], str(cputypes[0])),
                "filetype": None, "is64": is64, "fat": True}
    if magic not in thin:
        raise MachOError("not a Mach-O magic: %s" % magic.hex())
    endian, is64 = thin[magic]
    header_size = 32 if is64 else 28
    if len(data) < header_size:
        raise MachOError("truncated mach header")
    cputype, cpusubtype, filetype = struct.unpack_from(endian + "3I", data, 4)
    return {"cputype": cputype, "cputypes": [cputype],
            "arch": CPU_TYPE_NAME.get(cputype, str(cputype)),
            "filetype": filetype, "is64": is64, "fat": False}


def read_macho(path):
    with open(path, "rb") as f:
        return parse_macho(f.read())


def detect_host(commands):
    machine = platform.machine() or ""
    native = "arm64" if machine.lower() in ("arm64", "aarch64") else (
        "x86_64" if machine.lower() in ("x86_64", "amd64") else None)
    uname_machine = None
    if sys.platform == "darwin":
        r = run(["sysctl", "-n", "hw.machine"])
        commands.append(r)
        if r["rc"] == 0:
            uname_machine = r["stdout"]
    return {"machine": machine, "sysctl_hw_machine": uname_machine,
            "native_arch": native, "os": platform.system(),
            "os_version": platform.version()}


def detect_sdk(commands):
    info = {"path": None, "version": None, "archs": [], "proven": False,
            "reason": None}
    r = run(["xcrun", "--show-sdk-path"])
    commands.append(r)
    if r["rc"] != 0 or not r["stdout"]:
        info["reason"] = "xcrun --show-sdk-path failed: %s" % (r["stderr"] or "no output")
        return info
    info["path"] = r["stdout"].splitlines()[0]
    settings = os.path.join(info["path"], "SDKSettings.json")
    try:
        with open(settings, "r", encoding="utf-8") as f:
            data = json.load(f)
        macos = data["SupportedTargets"]["macosx"]
        info["version"] = data.get("Version")
        info["archs"] = sorted(macos.get("Archs", []))
        info["proven"] = bool(info["archs"])
    except (OSError, ValueError, KeyError, TypeError) as e:
        info["reason"] = "unreadable SDKSettings.json: %s" % e
    return info


def detect_clang(clang, commands):
    info = {"path": clang, "version": None, "targets": [], "proven": False,
            "reason": None}
    if not clang:
        info["reason"] = "no clang executable found"
        return info
    v = run([clang, "--version"])
    commands.append(v)
    if v["rc"] == 0:
        info["version"] = v["stdout"].splitlines()[0] if v["stdout"] else None
    t = run([clang, "--print-targets"])
    commands.append(t)
    if t["rc"] == 0:
        seen = False
        for line in t["stdout"].splitlines():
            if "Registered Targets:" in line:
                seen = True
                continue
            if seen and line.strip():
                info["targets"].append(line.split()[0])
    info["x86_64_backend"] = "x86-64" in info["targets"]
    info["arm64_backend"] = any(x in info["targets"] for x in ("aarch64", "arm64"))
    info["proven"] = bool(info["version"]) and bool(info["targets"])
    if not info["proven"]:
        info["reason"] = "clang --version/--print-targets did not succeed"
    return info


def _probe_arch(arch, deployment, sdk, clang, commands, workdir):
    """Build, header-verify, and attempt to run a real probe for one arch."""
    triple = TARGETS[arch].format(ver=deployment)
    res = {"target": triple, "build": {"proven": False, "kind": None,
                                        "cputype": None, "macho": None,
                                        "reason": None},
           "run": {"status": "not_run", "proc_translated": None,
                   "native": False, "translated": False, "error": None}}
    if not sdk.get("path") or not clang:
        res["build"]["reason"] = "no SDK or clang available"
        return res
    src = os.path.join(workdir, "probe_%s.c" % arch)
    exe = os.path.join(workdir, "probe_%s" % arch)
    with open(src, "w", encoding="utf-8") as f:
        f.write(PROBE_SOURCE)
    c = run([clang, "-target", triple, "-isysroot", sdk["path"], src, "-o", exe],
            cwd=workdir)
    commands.append(c)
    if c["rc"] != 0 or not os.path.isfile(exe):
        res["build"]["reason"] = "compile/link failed: %s" % (
            c["stderr"] or c["stdout"] or "no output")
        return res
    try:
        header = read_macho(exe)
    except (OSError, MachOError) as e:
        res["build"]["reason"] = "Mach-O header unreadable: %s" % e
        return res
    res["build"]["cputype"] = header["cputype"]
    res["build"]["macho"] = " ".join(
        ["Mach-O"] + (["64-bit"] if header["is64"] else []) +
        (["fat"] if header["fat"] else []) + [header["arch"]])
    for tool in ("file", "lipo"):
        if shutil.which(tool):
            argv = [tool] + (["-info"] if tool == "lipo" else []) + [exe]
            commands.append(run(argv, cwd=workdir))
    if header["cputype"] != EXPECTED_CPU[arch] or header["fat"]:
        res["build"]["reason"] = "cputype %s is not %s" % (
            header["cputype"], EXPECTED_CPU[arch])
        return res
    res["build"]["proven"] = True
    res["build"]["kind"] = "native" if arch == detect_native_arch() else "cross"

    x = run([exe], cwd=workdir)
    commands.append(x)
    if x["rc"] != 0:
        res["run"]["status"] = "failed"
        res["run"]["error"] = (x["stderr"] or x["stdout"] or
                               "exit %s" % x["rc"])
        return res
    vals = {}
    for line in x["stdout"].splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            vals[k.strip()] = v.strip()
    if vals.get("PROBE_OK") != "1":
        res["run"]["status"] = "unproven"
        res["run"]["error"] = "probe did not report PROBE_OK=1"
        return res
    try:
        translated = int(vals.get("PROC_TRANSLATED", "-1"))
    except ValueError:
        translated = -1
    res["run"]["proc_translated"] = translated
    # Fail closed: a foreign-arch binary that claims to be untranslated is an
    # inconsistency, not evidence of native execution.
    host = detect_native_arch()
    if translated == 1:
        res["run"]["status"] = "translated"
        res["run"]["translated"] = True
    elif translated == 0 and arch == host:
        res["run"]["status"] = "native"
        res["run"]["native"] = True
    elif translated == 0:
        res["run"]["status"] = "inconsistent_untranslated"
        res["run"]["error"] = ("proc_translated=0 for %s on a %s host"
                               % (arch, host))
    else:
        res["run"]["status"] = "unproven"
        res["run"]["error"] = "proc_translated unavailable (%d)" % translated
    return res


def detect_native_arch():
    m = platform.machine().lower()
    if m in ("arm64", "aarch64"):
        return "arm64"
    if m in ("x86_64", "amd64"):
        return "x86_64"
    return None


def claims_from(report):
    """Derive only the claims this machine can actually support."""
    host = report["host"]["native_arch"]
    archs = report["architectures"]
    claims = {}
    for arch in ("arm64", "x86_64"):
        run_info = archs[arch]["run"]
        # Native execution requires BOTH a matching host and an in-process
        # reading of proc_translated == 0. Rosetta is explicitly excluded.
        claims["%s_native_execution" % arch] = bool(
            host == arch and run_info["native"])
        claims["%s_cross_compile" % arch] = bool(
            archs[arch]["build"]["proven"] and
            archs[arch]["build"]["kind"] == "cross" and host != arch)
        claims["%s_build_proven" % arch] = bool(archs[arch]["build"]["proven"])
        claims["%s_run_via_rosetta" % arch] = bool(
            host != arch and run_info["translated"])
    return claims


def unmet_requirements(report, require_build=(), require_native=()):
    """Fail-closed gate: list requirements that are not PROVEN true."""
    claims = report["claims"]
    unmet = []
    for arch in require_build:
        if not claims.get("%s_build_proven" % arch, False):
            unmet.append("build for %s is not proven" % arch)
    for arch in require_native:
        if not claims.get("%s_native_execution" % arch, False):
            unmet.append("native execution of %s is not proven" % arch)
    return unmet


def probe(deployment="11", clang=None):
    commands = []
    clang = clang or shutil.which("clang") or "/usr/bin/clang"
    host = detect_host(commands)
    sdk = detect_sdk(commands)
    compiler = detect_clang(clang, commands)
    rosetta = {"present": any(os.path.exists(p) for p in ROSETTA_PATHS),
               "paths": {p: os.path.exists(p) for p in ROSETTA_PATHS}}
    clang_exe = compiler["path"]
    with tempfile.TemporaryDirectory(prefix="macos-target-probe-") as wd:
        archs = {a: _probe_arch(a, deployment, sdk, clang_exe, commands, wd)
                 for a in ("arm64", "x86_64")}
    report = {
        "schema": SCHEMA,
        "host": host,
        "sdk": sdk,
        "clang": compiler,
        "deployment_target": deployment,
        "rosetta": rosetta,
        "architectures": archs,
        "limits": [
            "Rosetta 2 is binary translation, not native x86_64 execution.",
            "An x86_64-only Mach-O on an arm64 Mac without Rosetta fails with "
            "'Bad CPU type in executable' (errno EBADARCH).",
            "A Mach-O header proves which architecture was BUILT, never that "
            "the code was executed natively.",
            "The SDK's advertised Archs list is not evidence of a successful "
            "build; every row here comes from a compiled file's header.",
        ],
        "commands": commands,
    }
    report["claims"] = claims_from(report)
    return report


def format_human(report):
    out = []
    out.append("macOS target probe (%s)" % report["schema"])
    h = report["host"]
    out.append("  host: %s (native_arch=%s, os=%s %s)" % (
        h["machine"], h["native_arch"], h["os"], h["os_version"]))
    s = report["sdk"]
    out.append("  SDK: %s (version=%s, archs=%s, proven=%s)" % (
        s["path"], s["version"], ",".join(s["archs"]) or "-", s["proven"]))
    c = report["clang"]
    out.append("  clang: %s (%s)" % (c["path"], c["version"]))
    out.append("  Rosetta 2 present: %s" % report["rosetta"]["present"])
    for arch in ("arm64", "x86_64"):
        a = report["architectures"][arch]
        b, r = a["build"], a["run"]
        out.append("  %s:" % arch)
        out.append("    build: %s (%s, cputype=%s, %s)" % (
            b["proven"], b["kind"] or "-", b["cputype"],
            b["reason"] or b["macho"]))
        out.append("    run:   %s (proc_translated=%s%s)" % (
            r["status"], r["proc_translated"],
            "; " + r["error"] if r["error"] else ""))
    out.append("  claims:")
    for k, v in sorted(report["claims"].items()):
        out.append("    %-32s %s" % (k, v))
    out.append("  limits:")
    for line in report["limits"]:
        out.append("    - " + line)
    out.append("  commands (%d):" % len(report["commands"]))
    for cmd in report["commands"]:
        out.append("    $ %s   [rc=%s]" % (
            " ".join(cmd["argv"]), cmd["rc"]))
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--json", action="store_true", help="emit JSON report")
    ap.add_argument("--deployment-target", default="11",
                    help="macOS deployment target (default: 11)")
    ap.add_argument("--clang", default=None, help="clang executable to use")
    ap.add_argument("--require-build", action="append", default=[],
                    metavar="ARCH", help="exit non-zero unless build is proven")
    ap.add_argument("--require-native", action="append", default=[],
                    metavar="ARCH", help="exit non-zero unless NATIVE run is proven")
    ap.add_argument("--out", default=None, help="also write the JSON report here")
    args = ap.parse_args(argv)

    for arch in list(args.require_build) + list(args.require_native):
        if arch not in TARGETS:
            ap.error("unknown architecture: %s (choose arm64 or x86_64)" % arch)

    report = probe(deployment=args.deployment_target, clang=args.clang)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as f:
            json.dump(report, f, indent=2, sort_keys=True)
            f.write("\n")
    print(json.dumps(report, indent=2, sort_keys=True) if args.json
          else format_human(report))
    unmet = unmet_requirements(report, args.require_build, args.require_native)
    if unmet:
        print("FAIL-CLOSED: " + "; ".join(unmet), file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
