#!/usr/bin/env python3
"""Assemble a native Linux CMake project from a generated PE32+ recompilation.

PR #175's ``tools/linux_matrix.py`` builds and runs generated projects in a
prebuilt Linux container, but its project generator only handles PE32 x86.
This tool supplies the missing PE32+ half, using the same shape (a CMakeLists.txt
plus ``src/``) so linux_matrix needs no changes:

    python3 -m tools.disasm.disasm64 game.exe --funcs-txt funcs.txt
    python3 -m tools.lift.generate64 game.exe funcs.txt gen/
    python3 -m tools.x64_project --exe game.exe --gen gen/ --out project/
    python3 -m tools.linux_matrix --project project/ --out results/ \
        --original game.exe

The emitted project embeds the ORIGINAL bytes as a C array, maps them at the
PE's ImageBase, fills IAT slots with HLE sentinels, provides a modelled TEB for
GS-relative guest accesses and calls dispatch() on the entry point. Imports are
implemented in runtime/recomp64_cpu/host64_linux.c; an unimplemented one exits
with a distinct code instead of being silently faked.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNTIME = ROOT / 'runtime' / 'recomp64_cpu'


def make_project_name(exe: Path) -> str:
    stem = re.sub(r'[^A-Za-z0-9_-]', '_', exe.stem)
    return (stem + '_x64').lstrip('_') or 'guest_x64'


def read_pe(path: Path) -> dict:
    data = path.read_bytes()
    if len(data) < 0x40 or data[:2] != b'MZ':
        raise SystemExit(f'{path}: not an MZ image')
    pe = struct.unpack_from('<I', data, 0x3c)[0]
    if pe + 24 > len(data) or data[pe:pe + 4] != b'PE\0\0':
        raise SystemExit(f'{path}: no PE signature at {pe:#x}')
    machine = struct.unpack_from('<H', data, pe + 4)[0]
    if machine != 0x8664:
        raise SystemExit(f'{path}: machine {machine:#x} is not AMD64 (0x8664)')
    nsec = struct.unpack_from('<H', data, pe + 6)[0]
    optsz = struct.unpack_from('<H', data, pe + 20)[0]
    opt = pe + 24
    magic = struct.unpack_from('<H', data, opt)[0]
    if magic != 0x20b:
        raise SystemExit(f'{path}: optional magic {magic:#x} is not PE32+ (0x20b)')
    # PE32+ optional header: entry +16 (u32), ImageBase +24 (u64),
    # SizeOfImage +56 (u32), SizeOfHeaders +60 (u32). Reading these as one
    # '<IQII' packs at +20 instead of +24 -- BaseOfCode, not ImageBase.
    entry = struct.unpack_from('<I', data, opt + 16)[0]
    base = struct.unpack_from('<Q', data, opt + 24)[0]
    soi = struct.unpack_from('<I', data, opt + 56)[0]
    soh = struct.unpack_from('<I', data, opt + 60)[0]
    return {
        'data': data, 'image_base': base, 'entry_rva': entry,
        'size_of_image': soi, 'size_of_headers': soh,
        'sections': nsec, 'optional_size': optsz,
    }


def c_byte_array(data: bytes, name: str = 'guest_image') -> str:
    lines = [f'/* Embedded original PE32+ image: {len(data)} bytes. */',
             f'const unsigned char {name}[] = {{']
    for i in range(0, len(data), 12):
        chunk = data[i:i + 12]
        lines.append('    ' + ' '.join(f'0x{b:02x},' for b in chunk))
    lines.append('};')
    lines.append(f'const unsigned long {name}_len = sizeof({name});')
    return '\n'.join(lines) + '\n'


CMAKELISTS = """# Generated by tools/x64_project.py -- do not edit.
cmake_minimum_required(VERSION 3.20)
project({name} C)
set(CMAKE_C_STANDARD 17)
if(NOT MSVC)
    # Mechanically-lifted C is correct-but-noisy; warnings are not the gate.
    add_compile_options(-w -O1)
endif()
enable_language(C)
file(GLOB GEN_SOURCES "${{CMAKE_CURRENT_SOURCE_DIR}}/src/recomp_*.c")
add_executable({name}
    src/main.c
    src/guest_image.c
    ${{GEN_SOURCES}}
)
target_include_directories({name} PRIVATE src)
target_link_libraries({name} PRIVATE m)
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--exe', type=Path, required=True, help='original PE32+ image')
    ap.add_argument('--gen', type=Path, required=True, help='generate64.py output directory')
    ap.add_argument('--out', type=Path, required=True, help='CMake project directory')
    ap.add_argument('--name', help='target name (default: <exe-stem>_x64)')
    args = ap.parse_args(argv)

    pe = read_pe(args.exe)
    gen = args.gen.resolve()
    out = args.out.resolve()
    if not (gen / 'recomp_dispatch.c').is_file():
        raise SystemExit(f'{gen}: no recomp_dispatch.c (run generate64.py first)')
    name = args.name or make_project_name(args.exe)
    src = out / 'src'
    if src.exists():
        shutil.rmtree(src)
    src.mkdir(parents=True)

    for pattern in ('recomp_*.c', 'recomp_*.h'):
        for f in sorted(gen.glob(pattern)):
            shutil.copy2(f, src / f.name)
    for h in ('cpu64.h', 'eh64.h', 'host64_linux.c'):
        shutil.copy2(RUNTIME / h, src / ('main.c' if h.endswith('_linux.c') else h))
    (src / 'guest_image.c').write_text(c_byte_array(pe['data']))
    (out / 'CMakeLists.txt').write_text(CMAKELISTS.format(name=name))
    (out / 'project_meta.json').write_text(json.dumps({
        'schema': 1,
        'original': str(args.exe.resolve()),
        'generator': 'tools/x64_project.py',
        'name': name,
        'image_base': pe['image_base'],
        'entry_rva': pe['entry_rva'],
        'entry_va': pe['image_base'] + pe['entry_rva'],
        'size_of_image': pe['size_of_image'],
        'sections': pe['sections'],
        'guest_bytes': len(pe['data']),
    }, indent=2) + '\n')

    guest_len = len(pe['data'])
    base = pe['image_base']
    print('[*] %s: %d guest bytes, base %#x, entry %#x -> %s'
          % (name, guest_len, base, base + pe['entry_rva'], out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
