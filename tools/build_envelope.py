#!/usr/bin/env python3
"""Deterministic build resource-envelope verdicts from supplied readings (#26).

Joins two caller-supplied inputs -- a *declared resource envelope* (a JSON file
of per-metric limits) and *resource measurements* (CLI flags and/or an optional
JSON file) -- and emits a deterministic JSON or Markdown summary. No build is
run, no path or limit is built in, and no number is measured, estimated or
derived by this tool: every value shown is one that was supplied by the caller.

Four metrics are always reported, in a fixed order:

* ``generated_bytes``  -- generated C/output bytes (limit: ``max``)
* ``peak_rss_bytes``   -- peak resident bytes (limit: ``max``)
* ``wall_seconds``     -- wall-clock seconds (limit: ``max``)
* ``disk_free_bytes``  -- free bytes on the build disk (limit: ``min``)

A metric is WITHIN when its reading satisfies the declared limit (inclusive),
OVER when it breaches it, and NOT TESTED when the reading is null/absent or the
envelope does not declare a limit for it. A NOT TESTED reading is never coerced
to zero: the value stays ``null`` and the verdict stays ``NOT TESTED``. A
present but malformed reading (negative, boolean, non-finite, string where a
number is required, or a CLI/file disagreement) is rejected outright: the CLI
writes no report and exits 2. No speedup, ratio, baseline or other derived
performance claim is computed.

Envelope JSON schema (all four limits are optional; unknown metric names,
missing/multiple directions and malformed limits are rejected)::

    {
      "schema": 1,
      "limits": {
        "generated_bytes": {"max": 3129026103},
        "peak_rss_bytes": {"max": 2147483648},
        "wall_seconds": {"max": 3600},
        "disk_free_bytes": {"min": 1073741824}
      }
    }

Measurements may be given as ``--generated-bytes N --peak-rss-bytes N
--wall-seconds S --disk-free-bytes N`` and/or in a JSON object whose fields
are top-level or nested under ``measurements`` or ``resources``. Omitting a
field means NOT TESTED; an explicit JSON ``null`` means the same thing.

Usage::

    python3 -m tools.build_envelope --envelope <limits.json> \
        [--measurements <readings.json>] [--generated-bytes N] \
        [--peak-rss-bytes N] [--wall-seconds S] [--disk-free-bytes N] \
        [--out-json <summary.json>] [--out-md <summary.md>] [--strict]

``--strict`` exits 1 unless the overall verdict is PASS (all four metrics
WITHIN). Tampered or unreadable inputs exit 2. With no output path, Markdown
is printed to stdout.
"""
from __future__ import annotations

import argparse
import json
import math
import re
import sys
from pathlib import Path
from typing import Any, NamedTuple

SCHEMA_VERSION = 1
GENERATOR = "tools/build_envelope.py"

WITHIN = "WITHIN"
OVER = "OVER"
NOT_TESTED = "NOT TESTED"

METHOD = (
    "WITHIN when value<=max (value>=min for disk_free_bytes), inclusive; "
    "OVER on breach; null/absent reading or undeclared limit = NOT TESTED "
    "(never 0); readings are transcribed only, no derived performance claims"
)

# Strict CLI grammars: no signs, bool words, NaNs, hex or underscore separators.
_BYTES_RE = re.compile(r"[0-9]+")
_SECONDS_RE = re.compile(
    r"(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)(?:[eE][+-]?[0-9]+)?")


class MetricSpec(NamedTuple):
    key: str
    label: str
    unit: str
    direction: str  # "max" for consumption metrics, "min" for disk free


# Fixed order -> deterministic Markdown/JSON. This is the output contract.
METRICS: tuple[MetricSpec, ...] = (
    MetricSpec("generated_bytes", "Generated bytes", "bytes", "max"),
    MetricSpec("peak_rss_bytes", "Peak RSS", "bytes", "max"),
    MetricSpec("wall_seconds", "Wall seconds", "s", "max"),
    MetricSpec("disk_free_bytes", "Disk free", "bytes", "min"),
)
_BY_KEY = {spec.key: spec for spec in METRICS}


class _Missing:
    """Sentinel for a field that is genuinely absent from a JSON object."""


MISSING = _Missing()


def load_json(path: Path) -> dict:
    """Load a JSON object from a caller-supplied path; fail closed on bad input."""
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError(f"{path}: expected a JSON object")
    return data


def _valid_number(value: Any, *, integer: bool) -> bool:
    """True only for a real, finite, non-negative int (or float for seconds)."""
    if isinstance(value, bool):  # bool is an int subclass: never a measurement
        return False
    if integer:
        return isinstance(value, int) and value >= 0
    if isinstance(value, int):
        return value >= 0
    if isinstance(value, float):
        return math.isfinite(value) and value >= 0.0
    return False


def _kind(spec: MetricSpec) -> str:
    return "integer" if spec.unit == "bytes" else "number"


def parse_envelope(data: dict) -> dict[str, dict]:
    """Validate a declared envelope and return ``key -> {"kind", "value"}``."""
    if not isinstance(data, dict):
        raise ValueError("envelope: expected a JSON object")
    limits_obj = data.get("limits")
    if not isinstance(limits_obj, dict):
        raise ValueError("envelope: 'limits' must be an object")

    limits: dict[str, dict] = {}
    for key, entry in limits_obj.items():
        if key not in _BY_KEY:
            raise ValueError(f"envelope: unknown metric {key!r}")
        spec = _BY_KEY[key]
        expected = spec.direction
        if not isinstance(entry, dict) or set(entry) != {expected}:
            raise ValueError(
                f"envelope: {key} must declare exactly '{expected}' "
                f"(no other direction or extra keys)")
        value = entry[expected]
        if not _valid_number(value, integer=(spec.unit == "bytes")):
            raise ValueError(
                f"envelope: {key} {expected}={value!r} is not a finite "
                f"non-negative {_kind(spec)}")
        limits[key] = {"kind": expected, "value": value}
    return limits


def parse_measurements(data: dict) -> dict[str, Any]:
    """Validate supplied readings; absent/null become ``None`` (NOT TESTED)."""
    if not isinstance(data, dict):
        raise ValueError("measurements: expected a JSON object")
    values: dict[str, Any] = {}
    for spec in METRICS:
        raw: Any = MISSING
        if spec.key in data:
            raw = data[spec.key]
        else:
            for container in ("measurements", "resources"):
                block = data.get(container)
                if isinstance(block, dict) and spec.key in block:
                    raw = block[spec.key]
                    break
        if raw is MISSING or raw is None:
            values[spec.key] = None
            continue
        if not _valid_number(raw, integer=(spec.unit == "bytes")):
            raise ValueError(
                f"{spec.key}: measurement {raw!r} is not a finite non-negative "
                f"{_kind(spec)}")
        values[spec.key] = raw
    return values


def parse_cli_value(spec: MetricSpec, text: str) -> Any:
    """Parse one strict CLI string into a validated reading."""
    flag = "--" + spec.key.replace("_", "-")
    if spec.unit == "bytes":
        if not _BYTES_RE.fullmatch(text):
            raise ValueError(
                f"{flag}: expected a non-negative integer, got {text!r}")
        return int(text)
    if not _SECONDS_RE.fullmatch(text):
        raise ValueError(
            f"{flag}: expected a finite non-negative seconds value, "
            f"got {text!r}")
    value = float(text)
    if not math.isfinite(value) or value < 0.0:
        raise ValueError(f"{flag}: value {text!r} is not finite and non-negative")
    return value


def merge_measurements(file_data: dict | None,
                       flags: dict[str, Any]) -> dict[str, Any]:
    """Merge optional file readings with CLI flags; conflicting evidence fails."""
    merged = parse_measurements(file_data if file_data is not None else {})
    for key, value in flags.items():
        if value is None:
            continue
        if merged[key] is not None and merged[key] != value:
            raise ValueError(
                f"{key}: CLI value {value!r} conflicts with measurement "
                f"file value {merged[key]!r}")
        merged[key] = value
    return merged


def analyse(measurements: dict, envelope: dict) -> dict:
    """Build a deterministic, JSON-serialisable envelope verdict summary.

    Neither input is mutated. Tampered inputs raise ``ValueError`` rather than
    producing a report that could be mistaken for clean evidence.
    """
    values = parse_measurements(measurements)
    limits = parse_envelope(envelope)

    metrics: list[dict] = []
    for spec in METRICS:
        value = values.get(spec.key)
        limit = limits.get(spec.key)
        if value is None or limit is None:
            verdict, shown = NOT_TESTED, None
        else:
            bound = limit["value"]
            ok = (value <= bound if limit["kind"] == "max" else value >= bound)
            verdict, shown = (WITHIN if ok else OVER), value
        metrics.append({
            "key": spec.key,
            "label": spec.label,
            "unit": spec.unit,
            "value": shown,
            "limit": dict(limit) if limit is not None else None,
            "verdict": verdict,
        })

    tested = [m for m in metrics if m["verdict"] != NOT_TESTED]
    over = [m for m in metrics if m["verdict"] == OVER]
    if over:
        overall = "FAIL"
    elif len(tested) == len(METRICS):
        overall = "PASS"
    elif tested:
        overall = "PARTIAL"
    else:
        overall = NOT_TESTED

    findings: list[str] = []
    untested = [m["key"] for m in metrics if m["verdict"] == NOT_TESTED]
    if untested:
        noun = "metric" if len(untested) == 1 else "metrics"
        findings.append(
            f"{len(untested)} {noun} NOT TESTED: {', '.join(untested)}")

    return {
        "schema": SCHEMA_VERSION,
        "generator": GENERATOR,
        "method": METHOD,
        "verdict": overall,
        "metrics_tested": len(tested),
        "metrics_over": len(over),
        "metrics": metrics,
        "findings": findings,
    }


def build_summary(measurements: dict, envelope: dict, *,
                  envelope_label: str | None = None,
                  measurements_label: str | None = None) -> dict:
    """``analyse`` plus caller-supplied provenance labels (no timestamps)."""
    summary = analyse(measurements, envelope)
    summary["envelope"] = envelope_label
    summary["measurements"] = measurements_label
    return summary


def dumps_json(summary: dict) -> str:
    """Canonical JSON: sorted keys, fixed indentation, trailing newline."""
    return json.dumps(summary, indent=2, sort_keys=True, ensure_ascii=True) + "\n"


def _fmt(value: Any, unit: str) -> str:
    if unit == "bytes":
        return f"{int(value)} B"
    return f"{value} {unit}"


def _fmt_limit(limit: dict | None, unit: str) -> str:
    if limit is None:
        return "not declared"
    sign = "<=" if limit["kind"] == "max" else ">="
    return f"{sign} {_fmt(limit['value'], unit)}"


def render_markdown(summary: dict) -> str:
    """Render a deterministic Markdown table from a summary."""
    lines = [
        "# Build resource envelope",
        "",
        f"Envelope: `{summary.get('envelope') or 'not supplied'}`",
        f"Measurements: `{summary.get('measurements') or 'not supplied'}`",
        "",
        "| Metric | Value | Limit | Verdict |",
        "|---|---|---|---|",
    ]
    for metric in summary["metrics"]:
        shown = (_fmt(metric["value"], metric["unit"])
                 if metric["verdict"] != NOT_TESTED else NOT_TESTED)
        lines.append(
            f"| {metric['label']} | {shown} | "
            f"{_fmt_limit(metric['limit'], metric['unit'])} | "
            f"{metric['verdict']} |")
    lines += [
        "",
        f"Verdict: **{summary['verdict']}** "
        f"({summary['metrics_tested']}/{len(summary['metrics'])} metrics "
        f"tested, {summary['metrics_over']} OVER)",
        "",
        "No derived performance claims: this report only compares supplied "
        "readings with the declared limits.",
        "",
        "## Findings",
        "",
    ]
    lines += [f"- {finding}" for finding in summary["findings"]] or ["- none"]
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--envelope", required=True, type=Path,
                    help="caller-supplied JSON file declaring per-metric limits")
    ap.add_argument("--measurements", type=Path,
                    help="optional caller-supplied JSON file of readings")
    for spec in METRICS:
        ap.add_argument("--" + spec.key.replace("_", "-"), dest=spec.key,
                        help=f"supplied {spec.label.lower()} reading")
    ap.add_argument("--out-json", type=Path, help="write the JSON summary here")
    ap.add_argument("--out-md", type=Path, help="write Markdown here")
    ap.add_argument("--strict", action="store_true",
                    help="exit 1 unless the overall verdict is PASS")
    args = ap.parse_args(argv)

    try:
        envelope = load_json(args.envelope)
        file_data = load_json(args.measurements) if args.measurements else None
        flags: dict[str, Any] = {}
        for spec in METRICS:
            raw = getattr(args, spec.key)
            if raw is not None:
                flags[spec.key] = parse_cli_value(spec, raw)
        measurements = merge_measurements(file_data, flags)
        supplied = ", ".join(sorted(flags))
        summary = build_summary(
            measurements, envelope,
            envelope_label=str(args.envelope),
            measurements_label=(
                str(args.measurements) if args.measurements
                else f"CLI flags ({supplied})" if supplied else "not supplied"))
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"build_envelope: {exc}", file=sys.stderr)
        return 2

    markdown = render_markdown(summary)
    if args.out_json:
        args.out_json.parent.mkdir(parents=True, exist_ok=True)
        args.out_json.write_text(dumps_json(summary), encoding="utf-8")
    if args.out_md:
        args.out_md.parent.mkdir(parents=True, exist_ok=True)
        args.out_md.write_text(markdown, encoding="utf-8")
    if not args.out_json and not args.out_md:
        print(markdown)

    if args.strict and summary["verdict"] != "PASS":
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
