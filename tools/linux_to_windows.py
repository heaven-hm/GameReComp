#!/usr/bin/env python3
"""Linux-host -> Windows-target build of REAL C source, then a real Wine run.

This is SOURCE-level cross-compilation. It does **not** translate Linux ELF or
macOS Mach-O binaries into Windows PE files. The name means "build on Linux for
Windows": it reuses :mod:`tools.win32_crossbuild`, which compiles real C with
MinGW-w64 (i686 -> PE32, x86-64 -> PE32+), and :mod:`tools.wine_oracle`, which
executes the resulting PE under the local Highball/CrossOver Wine engine.

No source is synthesised. If no pre-existing C source can be found, the tool
returns an explicit BLOCKED record; it never writes a placeholder ``main()``
just to produce a green result. PE header verification and the Wine run are
likewise fail-closed: every failure carries a stable ``code`` and the verbatim
compiler/Wine output where available.

This smoke test proves only that *this* C source builds to a PE and prints real
stdout under Wine. It is not evidence that a recompiler-generated game project
builds: those projects still include the POSIX ``runtime/win32hle`` layer and
remain blocked until that runtime is ported.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

from tools.pe.pe_analyze import analyze_pe
from tools.win32_crossbuild import cross_build, find_cc
from tools.wine_oracle import DEFAULT_BOTTLE, find_wine, run_original

REPO_ROOT = Path(__file__).resolve().parents[1]
MAIN_RE = re.compile(r"\bmain\s*\(")

# Ordered, pre-existing source locations. Nothing here is generated by this
# module: every candidate must already exist on the host and pass validation.
PREFERRED_SOURCES = (
    Path.home() / "Downloads" / "Other" / "gitHub_C" / "FloatMemory.c",
)
SOURCE_ROOTS = (
    Path.home() / "Downloads" / "Other" / "gitHub_C",
    Path.home() / "Downloads" / "recomp-apps" / "windows" / "cli-apps",
    REPO_ROOT / "tests" / "fixtures",
)

NO_REAL_SOURCE_DIAG = (
    "no real C source found; refusing to synthesise a source "
    "(source-level cross-build only, no ELF/Mach-O binary conversion)"
)


class SourceError(ValueError):
    """A source path was supplied but failed fail-closed validation."""

    def __init__(self, code: str, diagnostic: str):
        super().__init__(diagnostic)
        self.code = code
        self.diagnostic = diagnostic


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _validate_source(path: Path) -> dict:
    """Return provenance for a real C source, or raise :class:`SourceError`."""
    path = Path(path)
    if not path.is_file():
        raise SourceError("SOURCE_NOT_FOUND", f"source file not found: {path}")
    data = path.read_bytes()
    if not data.strip():
        raise SourceError("SOURCE_EMPTY", f"source file is empty: {path}")
    if not MAIN_RE.search(data.decode("utf-8", "replace")):
        raise SourceError("SOURCE_NO_MAIN",
                          f"source has no main() entry point: {path}")
    return {"path": str(path.resolve()), "sha256": _sha256(path),
            "bytes": len(data)}


def discover_sources(roots=None) -> list[dict]:
    """Find pre-existing, compilable-looking C sources on this host."""
    found: list[dict] = []
    seen: set[str] = set()

    def add(path: Path) -> None:
        key = str(path.resolve())
        if key in seen:
            return
        try:
            rec = _validate_source(path)
        except (SourceError, OSError):
            return
        seen.add(key)
        found.append(rec)

    if roots is None:  # an explicit roots argument is authoritative
        for path in PREFERRED_SOURCES:
            add(path)
    for root in (SOURCE_ROOTS if roots is None else roots):
        root = Path(root)
        if not root.is_dir():
            continue
        for path in sorted(root.glob("*.c")):
            add(path)
    return found


def resolve_source(explicit=None, roots=None) -> dict | None:
    """Explicit path wins; otherwise pick the first discovered real source."""
    if explicit is not None:
        return _validate_source(Path(explicit))
    sources = discover_sources(roots)
    return sources[0] if sources else None


def verify_pe_header(path: Path, bits: int) -> tuple[dict | None, str]:
    """Confirm MZ + PE headers and the expected PE32/PE32+ machine type."""
    path = Path(path)
    if not path.is_file():
        return None, f"PE output missing: {path}"
    head = path.read_bytes()[:2]
    if head != b"MZ":
        return None, "missing MZ magic in PE header"
    try:
        info = analyze_pe(str(path))
    except Exception as exc:  # malformed PE must fail closed, not crash
        return None, f"PE header parse failed: {exc}"
    expected_type = "PE32" if bits == 32 else "PE32+"
    expected_machine = "i386" if bits == 32 else "x86-64"
    if info.pe_type != expected_type or info.machine != expected_machine:
        return None, (f"PE header mismatch: got {info.pe_type!r}/{info.machine!r}, "
                      f"expected {expected_type!r}/{expected_machine!r}")
    return {"mz": True, "pe_type": info.pe_type, "machine": info.machine,
            "subsystem": info.subsystem, "bytes": path.stat().st_size}, ""


def _blocked(code: str, reason: str, **extra) -> dict:
    rec = {"status": "BLOCKED", "code": code, "reason": reason}
    rec.update(extra)
    return rec


def linux_to_windows(source=None, out: Path | None = None, bits: int = 64,
                     run: bool = True, bottle: Path = DEFAULT_BOTTLE,
                     timeout: int = 600, wine_timeout: int = 120,
                     wine: str | None = None, expected_stdout: str | None = None,
                     roots=None) -> dict:
    """Cross-build real C to PE, verify its header, and run it under Wine.

    Returns a JSON-serialisable record with ``status`` in {OK, FAIL, BLOCKED}
    and a stable ``code``. Compilation delegates to ``cross_build`` so this
    module adds orchestration and evidence, not a second build implementation.
    """
    if bits not in (32, 64):
        return _blocked("INVALID_BITS", f"bits must be 32 or 64, got {bits!r}")
    try:
        src = resolve_source(source, roots)
    except SourceError as exc:
        return _blocked(exc.code, exc.diagnostic)
    if src is None:
        searched = list(PREFERRED_SOURCES) + list(
            SOURCE_ROOTS if roots is None else roots)
        return _blocked("NO_REAL_SOURCE", NO_REAL_SOURCE_DIAG,
                        roots=[str(Path(r)) for r in searched])
    if out is None:
        return _blocked("NO_OUTPUT_PATH", "no PE output path was supplied")

    cc = find_cc(bits)
    if not cc:
        compiler = "i686-w64-mingw32-gcc" if bits == 32 else "x86_64-w64-mingw32-gcc"
        return _blocked("NO_MINGW_COMPILER", f"{compiler} not found on PATH",
                        source=src)

    out = Path(out)
    built = cross_build(Path(src["path"]).parent, out, bits,
                        [Path(src["path"])], timeout)
    base = {"source": src, "compiler": cc, "binary": str(out)}
    if built["status"] != "OK":
        code = "CROSSBUILD_BLOCKED" if built["status"] == "BLOCKED" \
            else "CROSSBUILD_FAIL"
        base.update(built)
        base["status"] = built["status"]
        base["code"] = code
        return base

    pe, err = verify_pe_header(out, bits)
    if pe is None:
        base.update({"status": "FAIL", "code": "PE_HEADER_INVALID",
                     "reason": err})
        return base
    base["pe"] = pe

    if not run:
        base.update({"status": "OK", "code": "PE_BUILT_NOT_RUN",
                     "note": "PE built and verified; Wine execution not requested"})
        return base

    wine = wine or find_wine()
    if not wine:
        base.update(_blocked("NO_WINE_ENGINE",
                             "no Wine engine found; PE built but runtime stdout "
                             "not verified (set RECOMP_WINE)"))
        return base

    try:
        result = run_original(wine, Path(bottle), out, [], wine_timeout)
    except (OSError, ValueError, subprocess.SubprocessError) as exc:
        base.update({"status": "FAIL", "code": "WINE_RUN_ERROR",
                     "reason": f"Wine execution failed: {exc}"})
        return base
    base["wine_run"] = result
    if result["exit_code"] == "TIMEOUT":
        base.update({"status": "FAIL", "code": "WINE_TIMEOUT",
                     "reason": f"Wine timed out after {wine_timeout}s"})
        return base
    if expected_stdout and expected_stdout not in result["stdout"]:
        base.update({"status": "FAIL", "code": "WINE_STDOUT_MISMATCH",
                     "reason": f"expected stdout substring not found: {expected_stdout!r}"})
        return base
    base.update({"status": "OK", "code": "PE_RAN_UNDER_WINE",
                 "note": ("one compiled C source ran under Wine; this does not "
                          "validate any recompiler-generated game project")})
    return base


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--source", type=Path, default=None,
                    help="path to an existing C source (default: discover one)")
    ap.add_argument("--out", type=Path, required=True, help="PE output path")
    ap.add_argument("--bits", type=int, choices=(32, 64), default=64)
    ap.add_argument("--bottle", type=Path, default=DEFAULT_BOTTLE)
    ap.add_argument("--timeout", type=int, default=600, help="compiler timeout")
    ap.add_argument("--wine-timeout", type=int, default=120)
    ap.add_argument("--wine", default=None, help="override Wine binary")
    ap.add_argument("--no-run", action="store_true",
                    help="build and verify the PE but skip the Wine run")
    ap.add_argument("--expected-stdout", default=None,
                    help="substring that must appear in real Wine stdout")
    ap.add_argument("--out-json", type=Path)
    args = ap.parse_args(argv)

    rec = linux_to_windows(source=args.source, out=args.out, bits=args.bits,
                           run=not args.no_run, bottle=args.bottle,
                           timeout=args.timeout, wine_timeout=args.wine_timeout,
                           wine=args.wine, expected_stdout=args.expected_stdout)
    text = json.dumps(rec, indent=2) + "\n"
    if args.out_json:
        args.out_json.parent.mkdir(parents=True, exist_ok=True)
        args.out_json.write_text(text)
    print(text)
    return {"OK": 0, "BLOCKED": 2}.get(rec["status"], 1)


if __name__ == "__main__":
    sys.exit(main())
